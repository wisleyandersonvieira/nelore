CREATE TABLE public.purchases (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  code BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  supplier_id UUID NOT NULL REFERENCES public.suppliers(id),
  store_id UUID NOT NULL REFERENCES public.stores(id),
  product_id UUID NOT NULL REFERENCES public.products(id),
  purchase_type TEXT NOT NULL CHECK (purchase_type IN ('animal', 'pregnancy', 'aspiration', 'recipient')),
  animal_id UUID REFERENCES public.animals(id),
  pregnancy_id UUID REFERENCES public.pregnancy_management(id),
  aspiration_id UUID REFERENCES public.aspiration_management(id),
  recipient_id UUID REFERENCES public.animals(id),
  item_name TEXT NOT NULL,
  item_code TEXT,
  description TEXT NOT NULL,
  document_type TEXT,
  document_number TEXT,
  negotiation_method TEXT,
  purchase_date DATE NOT NULL,
  issue_date DATE NOT NULL,
  first_due_date DATE NOT NULL,
  competence_date DATE NOT NULL,
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount > 0),
  installment_count INTEGER NOT NULL DEFAULT 1 CHECK (installment_count > 0),
  notes TEXT,
  created_by UUID NOT NULL REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT purchases_code_key UNIQUE (code),
  CONSTRAINT purchases_item_type_check CHECK (
    (purchase_type = 'animal' AND animal_id IS NOT NULL AND pregnancy_id IS NULL AND aspiration_id IS NULL AND recipient_id IS NULL) OR
    (purchase_type = 'pregnancy' AND animal_id IS NULL AND pregnancy_id IS NOT NULL AND aspiration_id IS NULL AND recipient_id IS NULL) OR
    (purchase_type = 'aspiration' AND animal_id IS NULL AND pregnancy_id IS NULL AND aspiration_id IS NOT NULL AND recipient_id IS NULL) OR
    (purchase_type = 'recipient' AND animal_id IS NULL AND pregnancy_id IS NULL AND aspiration_id IS NULL AND recipient_id IS NOT NULL)
  )
);

ALTER TABLE public.purchases ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view purchases"
ON public.purchases
FOR SELECT
USING (auth.uid() IS NOT NULL);

CREATE POLICY "Users can insert purchases"
ON public.purchases
FOR INSERT
WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Users can update purchases"
ON public.purchases
FOR UPDATE
USING (auth.uid() IS NOT NULL)
WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Users can delete purchases"
ON public.purchases
FOR DELETE
USING (auth.uid() IS NOT NULL);

CREATE INDEX idx_purchases_store_id ON public.purchases(store_id);
CREATE INDEX idx_purchases_supplier_id ON public.purchases(supplier_id);
CREATE INDEX idx_purchases_purchase_date ON public.purchases(purchase_date DESC);
CREATE INDEX idx_purchases_purchase_type ON public.purchases(purchase_type);

CREATE TRIGGER update_purchases_updated_at
BEFORE UPDATE ON public.purchases
FOR EACH ROW
EXECUTE FUNCTION public.update_updated_at_column();

ALTER TABLE public.accounts_payable
ADD COLUMN purchase_id UUID REFERENCES public.purchases(id) ON DELETE SET NULL;

CREATE UNIQUE INDEX idx_accounts_payable_purchase_id
ON public.accounts_payable(purchase_id)
WHERE purchase_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.create_purchase_with_payable(
  p_supplier_id UUID,
  p_purchase_type TEXT,
  p_item_id UUID,
  p_product_id UUID,
  p_purchase_date DATE,
  p_issue_date DATE,
  p_competence_date DATE,
  p_first_due_date DATE,
  p_total_amount NUMERIC,
  p_document_type TEXT DEFAULT NULL,
  p_document_number TEXT DEFAULT NULL,
  p_description TEXT DEFAULT NULL,
  p_notes TEXT DEFAULT NULL,
  p_negotiation_method TEXT DEFAULT NULL,
  p_installments JSONB DEFAULT '[]'::jsonb
)
RETURNS TABLE (
  purchase_id UUID,
  purchase_code BIGINT,
  account_payable_id UUID
)
LANGUAGE plpgsql
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_store_id UUID;
  v_item_name TEXT;
  v_item_code TEXT;
  v_purchase_description TEXT;
  v_payable_description TEXT;
  v_purchase_id UUID;
  v_purchase_code BIGINT;
  v_payable_id UUID;
  v_payable_item_id UUID;
  v_installment JSONB;
  v_installment_number INTEGER;
  v_installment_due_date DATE;
  v_installment_amount NUMERIC(12, 2);
  v_installment_total NUMERIC(12, 2) := 0;
  v_installment_count INTEGER := 0;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF p_supplier_id IS NULL THEN
    RAISE EXCEPTION 'Fornecedor é obrigatório.';
  END IF;

  IF p_product_id IS NULL THEN
    RAISE EXCEPTION 'Produto financeiro é obrigatório.';
  END IF;

  IF p_purchase_type NOT IN ('animal', 'pregnancy', 'aspiration', 'recipient') THEN
    RAISE EXCEPTION 'Tipo de compra inválido: %.', p_purchase_type;
  END IF;

  IF p_item_id IS NULL THEN
    RAISE EXCEPTION 'Item comprado é obrigatório.';
  END IF;

  IF p_purchase_date IS NULL OR p_issue_date IS NULL OR p_competence_date IS NULL OR p_first_due_date IS NULL THEN
    RAISE EXCEPTION 'Datas da compra, emissão, competência e primeiro vencimento são obrigatórias.';
  END IF;

  IF p_total_amount IS NULL OR p_total_amount <= 0 THEN
    RAISE EXCEPTION 'Valor total da compra deve ser maior que zero.';
  END IF;

  CASE p_purchase_type
    WHEN 'animal' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.animals
      WHERE id = p_item_id;
    WHEN 'pregnancy' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.pregnancy_management
      WHERE id = p_item_id;
    WHEN 'aspiration' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.aspiration_management
      WHERE id = p_item_id;
    WHEN 'recipient' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.animals
      WHERE id = p_item_id;
  END CASE;

  IF v_store_id IS NULL THEN
    RAISE EXCEPTION 'Registro de origem não encontrado para o tipo selecionado.';
  END IF;

  IF p_document_type IS NOT NULL AND p_document_number IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.accounts_payable ap
      WHERE ap.supplier_id = p_supplier_id
        AND ap.document_type = p_document_type
        AND ap.document_number = p_document_number
    ) THEN
      RAISE EXCEPTION 'Já existe um título com o mesmo tipo e número de documento para este fornecedor.';
    END IF;
  END IF;

  IF p_installments IS NULL OR jsonb_typeof(p_installments) <> 'array' OR jsonb_array_length(p_installments) = 0 THEN
    p_installments := jsonb_build_array(
      jsonb_build_object(
        'installment_number', 1,
        'due_date', p_first_due_date,
        'amount', ROUND(p_total_amount::numeric, 2)
      )
    );
  END IF;

  v_purchase_description := COALESCE(
    NULLIF(BTRIM(p_description), ''),
    FORMAT(
      '%s%s%s',
      INITCAP(p_purchase_type),
      CASE WHEN v_item_code IS NOT NULL AND v_item_code <> '' THEN ' ' || v_item_code ELSE '' END,
      CASE WHEN v_item_name IS NOT NULL AND v_item_name <> '' THEN ' - ' || v_item_name ELSE '' END
    )
  );

  INSERT INTO public.purchases (
    supplier_id,
    store_id,
    product_id,
    purchase_type,
    animal_id,
    pregnancy_id,
    aspiration_id,
    recipient_id,
    item_name,
    item_code,
    description,
    document_type,
    document_number,
    negotiation_method,
    purchase_date,
    issue_date,
    first_due_date,
    competence_date,
    total_amount,
    installment_count,
    notes,
    created_by
  )
  VALUES (
    p_supplier_id,
    v_store_id,
    p_product_id,
    p_purchase_type,
    CASE WHEN p_purchase_type = 'animal' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'pregnancy' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'aspiration' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'recipient' THEN p_item_id ELSE NULL END,
    v_item_name,
    v_item_code,
    v_purchase_description,
    p_document_type,
    p_document_number,
    p_negotiation_method,
    p_purchase_date,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(p_total_amount::numeric, 2),
    GREATEST(jsonb_array_length(p_installments), 1),
    NULLIF(BTRIM(p_notes), ''),
    v_user_id
  )
  RETURNING id, code
  INTO v_purchase_id, v_purchase_code;

  v_payable_description := FORMAT('Compra #%s - %s', v_purchase_code, v_purchase_description);

  INSERT INTO public.accounts_payable (
    supplier_id,
    purchase_id,
    description,
    document_type,
    document_number,
    issue_date,
    due_date,
    data_competencia,
    amount,
    total_amount,
    notes,
    status,
    store_id,
    account_id,
    created_by,
    updated_by
  )
  VALUES (
    p_supplier_id,
    v_purchase_id,
    v_payable_description,
    p_document_type,
    p_document_number,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(p_total_amount::numeric, 2),
    ROUND(p_total_amount::numeric, 2),
    NULLIF(BTRIM(p_notes), ''),
    'pending',
    v_store_id,
    NULL,
    v_user_id,
    v_user_id
  )
  RETURNING id
  INTO v_payable_id;

  INSERT INTO public.accounts_payable_items (
    account_payable_id,
    product_id,
    quantity,
    unit_price,
    total_price,
    store_id
  )
  VALUES (
    v_payable_id,
    p_product_id,
    1,
    ROUND(p_total_amount::numeric, 2),
    ROUND(p_total_amount::numeric, 2),
    v_store_id
  )
  RETURNING id
  INTO v_payable_item_id;

  INSERT INTO public.accounts_payable_item_allocations (
    account_payable_item_id,
    allocation_type,
    animal_id,
    aspiration_id,
    pregnancy_id,
    recipient_id
  )
  VALUES (
    v_payable_item_id,
    p_purchase_type,
    CASE WHEN p_purchase_type = 'animal' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'aspiration' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'pregnancy' THEN p_item_id ELSE NULL END,
    CASE WHEN p_purchase_type = 'recipient' THEN p_item_id ELSE NULL END
  );

  FOR v_installment IN
    SELECT value
    FROM jsonb_array_elements(p_installments)
  LOOP
    v_installment_count := v_installment_count + 1;
    v_installment_number := COALESCE((v_installment ->> 'installment_number')::INTEGER, v_installment_count);
    v_installment_due_date := (v_installment ->> 'due_date')::DATE;
    v_installment_amount := ROUND(COALESCE((v_installment ->> 'amount')::NUMERIC, 0)::numeric, 2);

    IF v_installment_due_date IS NULL THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter data de vencimento.';
    END IF;

    IF v_installment_amount <= 0 THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter valor maior que zero.';
    END IF;

    v_installment_total := v_installment_total + v_installment_amount;

    INSERT INTO public.accounts_payable_installments (
      account_payable_id,
      installment_number,
      due_date,
      amount,
      status
    )
    VALUES (
      v_payable_id,
      v_installment_number,
      v_installment_due_date,
      v_installment_amount,
      'pending'
    );
  END LOOP;

  IF ABS(v_installment_total - ROUND(p_total_amount::numeric, 2)) > 0.01 THEN
    RAISE EXCEPTION 'A soma das parcelas deve ser igual ao valor total da compra.';
  END IF;

  UPDATE public.purchases
  SET installment_count = v_installment_count
  WHERE id = v_purchase_id;

  RETURN QUERY
  SELECT v_purchase_id, v_purchase_code, v_payable_id;
END;
$$;
