CREATE OR REPLACE FUNCTION public.validate_semen_record()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_total_used NUMERIC(12, 2);
BEGIN
  NEW.name := BTRIM(COALESCE(NEW.name, ''));

  IF NEW.name = '' THEN
    RAISE EXCEPTION 'Nome / descrição é obrigatório.';
  END IF;

  IF NEW.quantity_initial IS NULL OR NEW.quantity_initial < 0 THEN
    RAISE EXCEPTION 'Quantidade inicial deve ser maior ou igual a zero.';
  END IF;

  IF TG_OP = 'UPDATE' THEN
    SELECT COALESCE(SUM(su.quantity_used), 0)
      INTO v_total_used
    FROM public.semen_utilizations su
    WHERE su.semen_id = NEW.id;

    IF NEW.quantity_initial < v_total_used THEN
      RAISE EXCEPTION 'Quantidade inicial não pode ser menor que a quantidade já utilizada.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER validate_semen_record_trigger
BEFORE INSERT OR UPDATE ON public.semen
FOR EACH ROW
EXECUTE FUNCTION public.validate_semen_record();

CREATE OR REPLACE FUNCTION public.validate_semen_utilization()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_quantity_initial NUMERIC(12, 2);
  v_total_other NUMERIC(12, 2);
BEGIN
  IF NEW.semen_id IS NULL THEN
    RAISE EXCEPTION 'Sêmen é obrigatório.';
  END IF;

  IF NEW.utilization_date IS NULL THEN
    RAISE EXCEPTION 'Data da utilização é obrigatória.';
  END IF;

  IF NEW.quantity_used IS NULL OR NEW.quantity_used <= 0 THEN
    RAISE EXCEPTION 'Quantidade utilizada deve ser maior que zero.';
  END IF;

  SELECT s.quantity_initial
    INTO v_quantity_initial
  FROM public.semen s
  WHERE s.id = NEW.semen_id
  FOR UPDATE;

  IF v_quantity_initial IS NULL THEN
    RAISE EXCEPTION 'Sêmen informado não foi encontrado.';
  END IF;

  SELECT COALESCE(SUM(su.quantity_used), 0)
    INTO v_total_other
  FROM public.semen_utilizations su
  WHERE su.semen_id = NEW.semen_id
    AND (TG_OP = 'INSERT' OR su.id <> NEW.id);

  IF v_total_other + NEW.quantity_used > v_quantity_initial THEN
    RAISE EXCEPTION 'Quantidade utilizada não pode ser maior que o saldo disponível.';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER validate_semen_utilization_trigger
BEFORE INSERT OR UPDATE ON public.semen_utilizations
FOR EACH ROW
EXECUTE FUNCTION public.validate_semen_utilization();

