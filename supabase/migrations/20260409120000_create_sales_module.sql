CREATE TABLE public.sales (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  code BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  client_id UUID NOT NULL REFERENCES public.suppliers(id),
  store_id UUID NOT NULL REFERENCES public.stores(id),
  product_id UUID NOT NULL REFERENCES public.products(id),
  sale_type TEXT NOT NULL CHECK (sale_type IN ('animal', 'pregnancy', 'aspiration', 'recipient')),
  animal_id UUID REFERENCES public.animals(id),
  pregnancy_id UUID REFERENCES public.pregnancy_management(id),
  aspiration_id UUID REFERENCES public.aspiration_management(id),
  recipient_id UUID REFERENCES public.animals(id),
  item_name TEXT NOT NULL,
  item_code TEXT,
  description TEXT NOT NULL,
  document_type TEXT,
  document_number TEXT,
  negotiation_method TEXT,
  sale_date DATE NOT NULL,
  issue_date DATE NOT NULL,
  first_due_date DATE NOT NULL,
  competence_date DATE NOT NULL,
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount > 0),
  installment_count INTEGER NOT NULL DEFAULT 1 CHECK (installment_count > 0),
  notes TEXT,
  created_by UUID NOT NULL REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT sales_code_key UNIQUE (code),
  CONSTRAINT sales_item_type_check CHECK (
    (sale_type = 'animal' AND animal_id IS NOT NULL AND pregnancy_id IS NULL AND aspiration_id IS NULL AND recipient_id IS NULL) OR
    (sale_type = 'pregnancy' AND animal_id IS NULL AND pregnancy_id IS NOT NULL AND aspiration_id IS NULL AND recipient_id IS NULL) OR
    (sale_type = 'aspiration' AND animal_id IS NULL AND pregnancy_id IS NULL AND aspiration_id IS NOT NULL AND recipient_id IS NULL) OR
    (sale_type = 'recipient' AND animal_id IS NULL AND pregnancy_id IS NULL AND aspiration_id IS NULL AND recipient_id IS NOT NULL)
  )
);

ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view sales"
ON public.sales
FOR SELECT
USING (auth.uid() IS NOT NULL);

CREATE POLICY "Users can insert sales"
ON public.sales
FOR INSERT
WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Users can update sales"
ON public.sales
FOR UPDATE
USING (auth.uid() IS NOT NULL)
WITH CHECK (auth.uid() IS NOT NULL);

CREATE POLICY "Users can delete sales"
ON public.sales
FOR DELETE
USING (auth.uid() IS NOT NULL);

CREATE INDEX idx_sales_store_id ON public.sales(store_id);
CREATE INDEX idx_sales_client_id ON public.sales(client_id);
CREATE INDEX idx_sales_sale_date ON public.sales(sale_date DESC);
CREATE INDEX idx_sales_sale_type ON public.sales(sale_type);

CREATE TRIGGER update_sales_updated_at
BEFORE UPDATE ON public.sales
FOR EACH ROW
EXECUTE FUNCTION public.update_updated_at_column();

ALTER TABLE public.accounts_receivable
ADD COLUMN sale_id UUID REFERENCES public.sales(id) ON DELETE SET NULL;

CREATE UNIQUE INDEX idx_accounts_receivable_sale_id
ON public.accounts_receivable(sale_id)
WHERE sale_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.create_sale_with_receivable(
  p_client_id UUID,
  p_sale_type TEXT,
  p_item_id UUID,
  p_product_id UUID,
  p_sale_date DATE,
  p_issue_date DATE,
  p_competence_date DATE,
  p_first_due_date DATE,
  p_total_amount NUMERIC,
  p_document_type TEXT DEFAULT NULL,
  p_document_number TEXT DEFAULT NULL,
  p_description TEXT DEFAULT NULL,
  p_notes TEXT DEFAULT NULL,
  p_negotiation_method TEXT DEFAULT NULL,
  p_installments JSONB DEFAULT '[]'::jsonb
)
RETURNS TABLE (
  sale_id UUID,
  sale_code BIGINT,
  account_receivable_id UUID
)
LANGUAGE plpgsql
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_store_id UUID;
  v_item_name TEXT;
  v_item_code TEXT;
  v_sale_description TEXT;
  v_receivable_description TEXT;
  v_sale_id UUID;
  v_sale_code BIGINT;
  v_receivable_id UUID;
  v_receivable_item_id UUID;
  v_installment JSONB;
  v_installment_number INTEGER;
  v_installment_due_date DATE;
  v_installment_amount NUMERIC(12, 2);
  v_installment_total NUMERIC(12, 2) := 0;
  v_installment_count INTEGER := 0;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF p_client_id IS NULL THEN
    RAISE EXCEPTION 'Cliente é obrigatório.';
  END IF;

  IF p_product_id IS NULL THEN
    RAISE EXCEPTION 'Produto financeiro é obrigatório.';
  END IF;

  IF p_sale_type NOT IN ('animal', 'pregnancy', 'aspiration', 'recipient') THEN
    RAISE EXCEPTION 'Tipo de venda inválido: %.', p_sale_type;
  END IF;

  IF p_item_id IS NULL THEN
    RAISE EXCEPTION 'Item vendido é obrigatório.';
  END IF;

  IF p_sale_date IS NULL OR p_issue_date IS NULL OR p_competence_date IS NULL OR p_first_due_date IS NULL THEN
    RAISE EXCEPTION 'Datas da venda, emissão, competência e primeiro vencimento são obrigatórias.';
  END IF;

  IF p_total_amount IS NULL OR p_total_amount <= 0 THEN
    RAISE EXCEPTION 'Valor total da venda deve ser maior que zero.';
  END IF;

  CASE p_sale_type
    WHEN 'animal' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.animals
      WHERE id = p_item_id;
    WHEN 'pregnancy' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.pregnancy_management
      WHERE id = p_item_id;
    WHEN 'aspiration' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.aspiration_management
      WHERE id = p_item_id;
    WHEN 'recipient' THEN
      SELECT store_id, name, code::TEXT
      INTO v_store_id, v_item_name, v_item_code
      FROM public.animals
      WHERE id = p_item_id;
  END CASE;

  IF v_store_id IS NULL THEN
    RAISE EXCEPTION 'Registro de origem não encontrado para o tipo selecionado.';
  END IF;

  IF p_document_type IS NOT NULL AND p_document_number IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.accounts_receivable ar
      WHERE ar.creditor_id = p_client_id
        AND ar.document_type = p_document_type
        AND ar.document_number = p_document_number
    ) THEN
      RAISE EXCEPTION 'Já existe um título com o mesmo tipo e número de documento para este cliente.';
    END IF;
  END IF;

  IF p_installments IS NULL OR jsonb_typeof(p_installments) <> 'array' OR jsonb_array_length(p_installments) = 0 THEN
    p_installments := jsonb_build_array(
      jsonb_build_object(
        'installment_number', 1,
        'due_date', p_first_due_date,
        'amount', ROUND(p_total_amount::numeric, 2)
      )
    );
  END IF;

  v_sale_description := COALESCE(
    NULLIF(BTRIM(p_description), ''),
    FORMAT(
      '%s%s%s',
      INITCAP(p_sale_type),
      CASE WHEN v_item_code IS NOT NULL AND v_item_code <> '' THEN ' ' || v_item_code ELSE '' END,
      CASE WHEN v_item_name IS NOT NULL AND v_item_name <> '' THEN ' - ' || v_item_name ELSE '' END
    )
  );

  INSERT INTO public.sales (
    client_id,
    store_id,
    product_id,
    sale_type,
    animal_id,
    pregnancy_id,
    aspiration_id,
    recipient_id,
    item_name,
    item_code,
    description,
    document_type,
    document_number,
    negotiation_method,
    sale_date,
    issue_date,
    first_due_date,
    competence_date,
    total_amount,
    installment_count,
    notes,
    created_by
  )
  VALUES (
    p_client_id,
    v_store_id,
    p_product_id,
    p_sale_type,
    CASE WHEN p_sale_type = 'animal' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'pregnancy' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'aspiration' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'recipient' THEN p_item_id ELSE NULL END,
    v_item_name,
    v_item_code,
    v_sale_description,
    p_document_type,
    p_document_number,
    p_negotiation_method,
    p_sale_date,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(p_total_amount::numeric, 2),
    GREATEST(jsonb_array_length(p_installments), 1),
    NULLIF(BTRIM(p_notes), ''),
    v_user_id
  )
  RETURNING id, code
  INTO v_sale_id, v_sale_code;

  v_receivable_description := FORMAT('Venda #%s - %s', v_sale_code, v_sale_description);

  INSERT INTO public.accounts_receivable (
    creditor_id,
    sale_id,
    description,
    document_type,
    document_number,
    issue_date,
    due_date,
    data_competencia,
    amount,
    total_amount,
    notes,
    status,
    store_id,
    account_id,
    created_by
  )
  VALUES (
    p_client_id,
    v_sale_id,
    v_receivable_description,
    p_document_type,
    p_document_number,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(p_total_amount::numeric, 2),
    ROUND(p_total_amount::numeric, 2),
    NULLIF(BTRIM(p_notes), ''),
    'pending',
    v_store_id,
    NULL,
    v_user_id
  )
  RETURNING id
  INTO v_receivable_id;

  INSERT INTO public.accounts_receivable_items (
    account_receivable_id,
    product_id,
    quantity,
    unit_price,
    total_price,
    store_id
  )
  VALUES (
    v_receivable_id,
    p_product_id,
    1,
    ROUND(p_total_amount::numeric, 2),
    ROUND(p_total_amount::numeric, 2),
    v_store_id
  )
  RETURNING id
  INTO v_receivable_item_id;

  INSERT INTO public.accounts_receivable_item_allocations (
    account_receivable_item_id,
    allocation_type,
    animal_id,
    aspiration_id,
    pregnancy_id,
    recipient_id
  )
  VALUES (
    v_receivable_item_id,
    p_sale_type,
    CASE WHEN p_sale_type = 'animal' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'aspiration' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'pregnancy' THEN p_item_id ELSE NULL END,
    CASE WHEN p_sale_type = 'recipient' THEN p_item_id ELSE NULL END
  );

  FOR v_installment IN
    SELECT value
    FROM jsonb_array_elements(p_installments)
  LOOP
    v_installment_count := v_installment_count + 1;
    v_installment_number := COALESCE((v_installment ->> 'installment_number')::INTEGER, v_installment_count);
    v_installment_due_date := (v_installment ->> 'due_date')::DATE;
    v_installment_amount := ROUND(COALESCE((v_installment ->> 'amount')::NUMERIC, 0)::numeric, 2);

    IF v_installment_due_date IS NULL THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter data de vencimento.';
    END IF;

    IF v_installment_amount <= 0 THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter valor maior que zero.';
    END IF;

    v_installment_total := v_installment_total + v_installment_amount;

    INSERT INTO public.accounts_receivable_installments (
      account_receivable_id,
      installment_number,
      due_date,
      amount
    )
    VALUES (
      v_receivable_id,
      v_installment_number,
      v_installment_due_date,
      v_installment_amount
    );
  END LOOP;

  IF ABS(v_installment_total - ROUND(p_total_amount::numeric, 2)) > 0.01 THEN
    RAISE EXCEPTION 'A soma das parcelas deve ser igual ao valor total da venda.';
  END IF;

  UPDATE public.sales
  SET installment_count = v_installment_count
  WHERE id = v_sale_id;

  RETURN QUERY
  SELECT v_sale_id, v_sale_code, v_receivable_id;
END;
$$;
