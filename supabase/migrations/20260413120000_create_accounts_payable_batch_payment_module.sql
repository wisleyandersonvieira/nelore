CREATE TABLE public.accounts_payable_payment_batches (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  batch_number BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  payment_account_id UUID NOT NULL,
  payment_account_type TEXT NOT NULL CHECK (payment_account_type IN ('current', 'cash', 'card', 'delivery')),
  payment_account_name TEXT NOT NULL,
  payment_date DATE NOT NULL,
  installments_count INTEGER NOT NULL DEFAULT 0 CHECK (installments_count >= 0),
  total_amount NUMERIC NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'reversed')),
  created_by UUID NOT NULL REFERENCES public.profiles(id),
  reversed_by UUID REFERENCES public.profiles(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  reversed_at TIMESTAMP WITH TIME ZONE,
  UNIQUE (batch_number)
);

CREATE TABLE public.accounts_payable_payment_batch_items (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  batch_id UUID NOT NULL REFERENCES public.accounts_payable_payment_batches(id) ON DELETE CASCADE,
  account_payable_id UUID NOT NULL REFERENCES public.accounts_payable(id) ON DELETE CASCADE,
  installment_id UUID NOT NULL REFERENCES public.accounts_payable_installments(id) ON DELETE CASCADE,
  payment_record_id UUID REFERENCES public.accounts_payable_payments(id) ON DELETE SET NULL,
  financial_transaction_id UUID REFERENCES public.financial_transactions(id) ON DELETE SET NULL,
  amount NUMERIC NOT NULL DEFAULT 0 CHECK (amount >= 0),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  UNIQUE (batch_id, installment_id)
);

CREATE INDEX idx_ap_payment_batches_created_at
