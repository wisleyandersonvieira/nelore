CREATE OR REPLACE FUNCTION public.create_accounts_payable_payment_batch(
  p_installment_ids UUID[],
  p_payment_date DATE,
  p_payment_account_id UUID,
  p_payment_account_type TEXT
)
RETURNS TABLE (
  batch_id UUID,
  batch_number BIGINT,
  installments_count INTEGER,
  total_amount NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_installment_ids UUID[];
  v_user_id UUID := auth.uid();
  v_user_role public.user_role;
  v_user_store_id UUID;
  v_user_matrix_id UUID;
  v_payment_account_name TEXT;
  v_allowed_store_ids UUID[];
  v_batch_id UUID;
  v_batch_number BIGINT;
  v_count INTEGER := 0;
  v_total NUMERIC := 0;
  v_expected_count INTEGER := 0;
  v_payment_record_id UUID;
  v_transaction_id UUID;
  v_account_id UUID;
  v_any_paid BOOLEAN;
  v_all_paid BOOLEAN;
  v_problem_document TEXT;
  v_problem_store UUID;
  r_installment RECORD;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF NOT public.user_has_permission('contas_pagar', 'write'::public.permission_type) THEN
    RAISE EXCEPTION 'Usuário sem permissão para baixar contas a pagar.';
  END IF;

  IF p_installment_ids IS NULL OR array_length(p_installment_ids, 1) IS NULL THEN
    RAISE EXCEPTION 'Selecione pelo menos uma parcela para a baixa em lote.';
  END IF;

  IF p_payment_date IS NULL THEN
    RAISE EXCEPTION 'Informe a data de pagamento do lote.';
  END IF;

  v_installment_ids := ARRAY(
    SELECT DISTINCT installment_id
    FROM unnest(p_installment_ids) AS installment_id
    WHERE installment_id IS NOT NULL
  );

  v_expected_count := COALESCE(array_length(v_installment_ids, 1), 0);
  IF v_expected_count = 0 THEN
    RAISE EXCEPTION 'Nenhuma parcela válida foi informada para a baixa em lote.';
  END IF;

  SELECT p.role, p.store_id, p.matrix_id
    INTO v_user_role, v_user_store_id, v_user_matrix_id
  FROM public.profiles p
  WHERE p.id = v_user_id;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND v_user_matrix_id IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.period_blocks pb
      WHERE pb.matrix_id = v_user_matrix_id
        AND pb.year = EXTRACT(YEAR FROM p_payment_date)::INTEGER
        AND pb.month = EXTRACT(MONTH FROM p_payment_date)::INTEGER
        AND pb.block_type = 'pagamento'::public.block_type
        AND 'contas_pagar' = ANY(pb.blocked_modules)
    ) THEN
      RAISE EXCEPTION 'O período %/% está bloqueado para pagamentos em Contas a Pagar.',
        EXTRACT(MONTH FROM p_payment_date)::INTEGER,
        EXTRACT(YEAR FROM p_payment_date)::INTEGER;
    END IF;
  END IF;

  IF p_payment_account_type = 'current' THEN
    SELECT ca.name,
           ARRAY(
             SELECT cas.store_id
             FROM public.current_account_stores cas
             WHERE cas.account_id = ca.id
           )
      INTO v_payment_account_name, v_allowed_store_ids
    FROM public.current_accounts ca
    WHERE ca.id = p_payment_account_id
      AND ca.is_active = true;
  ELSIF p_payment_account_type = 'cash' THEN
    SELECT ca.name,
           ARRAY(
             SELECT cas.store_id
             FROM public.cash_account_stores cas
             WHERE cas.account_id = ca.id
           )
      INTO v_payment_account_name, v_allowed_store_ids
    FROM public.cash_accounts ca
    WHERE ca.id = p_payment_account_id
      AND ca.is_active = true;
  ELSIF p_payment_account_type = 'card' THEN
    SELECT ca.name,
           ARRAY(
             SELECT cas.store_id
             FROM public.card_account_stores cas
             WHERE cas.account_id = ca.id
           )
      INTO v_payment_account_name, v_allowed_store_ids
    FROM public.card_accounts ca
    WHERE ca.id = p_payment_account_id
      AND ca.is_active = true;
  ELSIF p_payment_account_type = 'delivery' THEN
    SELECT da.name,
           ARRAY(
             SELECT das.store_id
             FROM public.delivery_account_stores das
             WHERE das.account_id = da.id
           )
      INTO v_payment_account_name, v_allowed_store_ids
    FROM public.delivery_accounts da
    WHERE da.id = p_payment_account_id
      AND da.is_active = true;
  ELSE
    RAISE EXCEPTION 'Tipo de conta financeira inválido: %.', p_payment_account_type;
  END IF;

  IF v_payment_account_name IS NULL THEN
    RAISE EXCEPTION 'Conta financeira não encontrada ou inativa.';
  END IF;

  IF COALESCE(array_length(v_allowed_store_ids, 1), 0) = 0 THEN
    RAISE EXCEPTION 'A conta financeira selecionada não possui lojas vinculadas.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_installments api
    JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
    WHERE api.id = ANY(v_installment_ids)
      AND v_user_role IS DISTINCT FROM 'admin'::public.user_role
      AND ap.store_id <> v_user_store_id
  ) THEN
    RAISE EXCEPTION 'Existem parcelas fora da loja permitida para este usuário.';
  END IF;

  SELECT ap.document_number, item.store_id
    INTO v_problem_document, v_problem_store
  FROM public.accounts_payable_installments api
  JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
  JOIN public.accounts_payable_items item ON item.account_payable_id = ap.id
  WHERE api.id = ANY(v_installment_ids)
    AND item.store_id IS NOT NULL
    AND NOT (item.store_id = ANY(v_allowed_store_ids))
  LIMIT 1;

  IF v_problem_store IS NOT NULL THEN
    RAISE EXCEPTION 'A conta financeira selecionada não está vinculada à loja de itens do documento %.',
      COALESCE(NULLIF(v_problem_document, ''), '[sem número]');
  END IF;

  FOR r_installment IN
    SELECT
      api.id,
      api.account_payable_id,
      api.installment_number,
      api.amount,
      api.payment_date,
      api.status,
      ap.description,
      ap.document_number,
      ap.store_id,
      ap.status AS account_status
    FROM public.accounts_payable_installments api
    JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
    WHERE api.id = ANY(v_installment_ids)
    ORDER BY api.due_date, api.id
    FOR UPDATE OF api, ap
  LOOP
    v_count := v_count + 1;
  END LOOP;

  IF v_count <> v_expected_count THEN
    RAISE EXCEPTION 'Uma ou mais parcelas não foram encontradas.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_installments api
    WHERE api.id = ANY(v_installment_ids)
      AND (
        api.payment_date IS NOT NULL
        OR api.status = 'pagamento_suspenso'
      )
  ) THEN
    RAISE EXCEPTION 'O lote contém parcelas já pagas, suspensas ou indisponíveis para baixa.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_payment_batch_items bi
    JOIN public.accounts_payable_payment_batches b ON b.id = bi.batch_id
    WHERE bi.installment_id = ANY(v_installment_ids)
      AND b.status = 'active'
  ) THEN
    RAISE EXCEPTION 'Uma ou mais parcelas já pertencem a um lote de baixa ativo.';
  END IF;

  INSERT INTO public.accounts_payable_payment_batches (
    payment_account_id,
    payment_account_type,
    payment_account_name,
    payment_date,
    created_by
  )
  VALUES (
    p_payment_account_id,
    p_payment_account_type,
    v_payment_account_name,
    p_payment_date,
    v_user_id
  )
  RETURNING id, accounts_payable_payment_batches.batch_number
  INTO v_batch_id, v_batch_number;

  v_count := 0;
  v_total := 0;

  FOR r_installment IN
    SELECT
      api.id,
      api.account_payable_id,
      api.installment_number,
      api.amount,
      ap.description,
      ap.store_id
    FROM public.accounts_payable_installments api
    JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
    WHERE api.id = ANY(v_installment_ids)
    ORDER BY api.due_date, api.id
  LOOP
    INSERT INTO public.accounts_payable_payments (
      installment_id,
      account_payable_id,
      payment_date,
      amount_paid,
      interest_amount,
      discount_amount,
      payment_account_id,
      payment_account_type,
      created_by
    )
    VALUES (
      r_installment.id,
      r_installment.account_payable_id,
      p_payment_date,
      r_installment.amount,
      0,
      0,
      p_payment_account_id,
      p_payment_account_type,
      v_user_id
    )
    RETURNING id INTO v_payment_record_id;

    UPDATE public.accounts_payable_installments
    SET
      payment_date = p_payment_date,
      status = 'paid'
    WHERE id = r_installment.id;

    INSERT INTO public.financial_transactions (
      store_id,
      account_id,
      transaction_type,
      amount,
      transaction_date,
      description,
      reference_id,
      reference_type,
      created_by
    )
    VALUES (
      r_installment.store_id,
      p_payment_account_id,
      'saida'::public.transaction_type,
      r_installment.amount,
      p_payment_date,
      format('Pagamento Parcela %s: %s', r_installment.installment_number, COALESCE(r_installment.description, 'Conta a pagar')),
      r_installment.id,
      'accounts_payable_installments',
      v_user_id
    )
    RETURNING id INTO v_transaction_id;

    INSERT INTO public.accounts_payable_payment_batch_items (
      batch_id,
      account_payable_id,
      installment_id,
      payment_record_id,
      financial_transaction_id,
      amount
    )
    VALUES (
      v_batch_id,
      r_installment.account_payable_id,
      r_installment.id,
      v_payment_record_id,
      v_transaction_id,
      r_installment.amount
    );

    v_count := v_count + 1;
    v_total := v_total + r_installment.amount;
  END LOOP;

  FOR v_account_id IN
    SELECT DISTINCT api.account_payable_id
    FROM public.accounts_payable_installments api
    WHERE api.id = ANY(v_installment_ids)
  LOOP
    SELECT
      bool_or(api.payment_date IS NOT NULL),
      bool_and(api.payment_date IS NOT NULL)
    INTO v_any_paid, v_all_paid
    FROM public.accounts_payable_installments api
    WHERE api.account_payable_id = v_account_id;

    UPDATE public.accounts_payable ap
    SET
      status = CASE
        WHEN COALESCE(v_all_paid, false) THEN 'paid'
        WHEN COALESCE(v_any_paid, false) THEN 'partial'
        ELSE 'pending'
      END,
      payment_date = CASE
        WHEN COALESCE(v_all_paid, false) THEN p_payment_date
        ELSE NULL
      END
    WHERE ap.id = v_account_id;
  END LOOP;

  UPDATE public.accounts_payable_payment_batches
  SET
    installments_count = v_count,
    total_amount = v_total
  WHERE id = v_batch_id;

  RETURN QUERY
  SELECT v_batch_id, v_batch_number, v_count, v_total;
END;
$$;

CREATE OR REPLACE FUNCTION public.reverse_accounts_payable_payment_batch(
  p_batch_id UUID
)
RETURNS TABLE (
  batch_id UUID,
  batch_number BIGINT,
  reversed_count INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_user_role public.user_role;
  v_user_store_id UUID;
  v_user_matrix_id UUID;
  v_batch RECORD;
  v_account_id UUID;
  v_any_paid BOOLEAN;
  v_all_paid BOOLEAN;
  v_reversed_count INTEGER := 0;
  r_item RECORD;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF NOT public.user_has_permission('contas_pagar', 'write'::public.permission_type) THEN
    RAISE EXCEPTION 'Usuário sem permissão para estornar lote de contas a pagar.';
  END IF;

  SELECT p.role, p.store_id, p.matrix_id
    INTO v_user_role, v_user_store_id, v_user_matrix_id
  FROM public.profiles p
  WHERE p.id = v_user_id;

  SELECT *
    INTO v_batch
  FROM public.accounts_payable_payment_batches b
  WHERE b.id = p_batch_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lote de baixa não encontrado.';
  END IF;

  IF v_batch.status <> 'active' THEN
    RAISE EXCEPTION 'Este lote já foi desfeito.';
  END IF;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND v_user_matrix_id IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.period_blocks pb
      WHERE pb.matrix_id = v_user_matrix_id
        AND pb.year = EXTRACT(YEAR FROM v_batch.payment_date)::INTEGER
        AND pb.month = EXTRACT(MONTH FROM v_batch.payment_date)::INTEGER
        AND pb.block_type = 'pagamento'::public.block_type
        AND 'contas_pagar' = ANY(pb.blocked_modules)
    ) THEN
      RAISE EXCEPTION 'O período %/% está bloqueado para pagamentos em Contas a Pagar.',
        EXTRACT(MONTH FROM v_batch.payment_date)::INTEGER,
        EXTRACT(YEAR FROM v_batch.payment_date)::INTEGER;
    END IF;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_payment_batch_items bi
    JOIN public.accounts_payable ap ON ap.id = bi.account_payable_id
    WHERE bi.batch_id = p_batch_id
      AND v_user_role IS DISTINCT FROM 'admin'::public.user_role
      AND ap.store_id <> v_user_store_id
  ) THEN
    RAISE EXCEPTION 'Existem parcelas deste lote fora da loja permitida para este usuário.';
  END IF;

  FOR r_item IN
    SELECT
      bi.id,
      bi.account_payable_id,
      bi.installment_id,
      bi.payment_record_id,
      bi.financial_transaction_id
    FROM public.accounts_payable_payment_batch_items bi
    WHERE bi.batch_id = p_batch_id
    ORDER BY bi.created_at, bi.id
  LOOP
    IF r_item.payment_record_id IS NOT NULL THEN
      DELETE FROM public.accounts_payable_payments
      WHERE id = r_item.payment_record_id;
    ELSE
      DELETE FROM public.accounts_payable_payments
      WHERE installment_id = r_item.installment_id;
    END IF;

    IF r_item.financial_transaction_id IS NOT NULL THEN
      DELETE FROM public.financial_transactions
      WHERE id = r_item.financial_transaction_id;
    ELSE
      DELETE FROM public.financial_transactions
      WHERE reference_id = r_item.installment_id
        AND reference_type = 'accounts_payable_installments';
    END IF;

    UPDATE public.accounts_payable_installments
    SET
      payment_date = NULL,
      status = 'pending'
    WHERE id = r_item.installment_id;

    v_reversed_count := v_reversed_count + 1;
  END LOOP;

  FOR v_account_id IN
    SELECT DISTINCT bi.account_payable_id
    FROM public.accounts_payable_payment_batch_items bi
    WHERE bi.batch_id = p_batch_id
  LOOP
    SELECT
      bool_or(api.payment_date IS NOT NULL),
      bool_and(api.payment_date IS NOT NULL)
    INTO v_any_paid, v_all_paid
    FROM public.accounts_payable_installments api
    WHERE api.account_payable_id = v_account_id;

    UPDATE public.accounts_payable ap
    SET
      status = CASE
        WHEN COALESCE(v_all_paid, false) THEN 'paid'
        WHEN COALESCE(v_any_paid, false) THEN 'partial'
        ELSE 'pending'
      END,
      payment_date = CASE
        WHEN COALESCE(v_any_paid, false) THEN ap.payment_date
        ELSE NULL
      END
    WHERE ap.id = v_account_id;
  END LOOP;

  UPDATE public.accounts_payable_payment_batches
  SET
    status = 'reversed',
    reversed_at = now(),
    reversed_by = v_user_id
  WHERE id = p_batch_id;

  RETURN QUERY
  SELECT v_batch.id, v_batch.batch_number, v_reversed_count;
END;
$$;

