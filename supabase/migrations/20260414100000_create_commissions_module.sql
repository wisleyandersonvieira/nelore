CREATE OR REPLACE FUNCTION public.create_commission_with_payable(
  p_auction_id UUID,
  p_supplier_id UUID,
  p_commission_kind TEXT,
  p_default_percentage NUMERIC,
  p_product_id UUID,
  p_commission_date DATE,
  p_issue_date DATE,
  p_competence_date DATE,
  p_first_due_date DATE,
  p_document_type TEXT DEFAULT NULL,
  p_document_number TEXT DEFAULT NULL,
  p_description TEXT DEFAULT NULL,
  p_notes TEXT DEFAULT NULL,
  p_negotiation_method TEXT DEFAULT NULL,
  p_items JSONB DEFAULT '[]'::jsonb,
  p_installments JSONB DEFAULT '[]'::jsonb
)
RETURNS TABLE (
  commission_id UUID,
  commission_code BIGINT,
  account_payable_id UUID
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_user_role public.user_role;
  v_user_store_id UUID;
  v_store_id UUID;
  v_auction_name TEXT;
  v_description TEXT;
  v_payable_description TEXT;
  v_total_amount NUMERIC(12, 2) := 0;
  v_commission_id UUID;
  v_commission_code BIGINT;
  v_payable_id UUID;
  v_payable_item_id UUID;
  v_item JSONB;
  v_item_id UUID;
  v_item_type TEXT;
  v_item_store_id UUID;
  v_item_name TEXT;
  v_item_code TEXT;
  v_purchase_amount NUMERIC(12, 2);
  v_item_percentage NUMERIC(7, 4);
  v_item_amount NUMERIC(12, 2);
  v_source_type TEXT;
  v_display_order INTEGER := 0;
  v_installment JSONB;
  v_installment_count INTEGER := 0;
  v_installment_number INTEGER;
  v_installment_due_date DATE;
  v_installment_amount NUMERIC(12, 2);
  v_installment_total NUMERIC(12, 2) := 0;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF NOT public.user_has_permission('contas_pagar', 'write'::public.permission_type) THEN
    RAISE EXCEPTION 'Usuário sem permissão para cadastrar comissões.';
  END IF;

  IF p_auction_id IS NULL THEN
    RAISE EXCEPTION 'Leilão é obrigatório.';
  END IF;

  IF p_supplier_id IS NULL THEN
    RAISE EXCEPTION 'Fornecedor é obrigatório.';
  END IF;

  IF p_product_id IS NULL THEN
    RAISE EXCEPTION 'Produto financeiro é obrigatório.';
  END IF;

  IF p_commission_kind NOT IN ('purchase', 'sale') THEN
    RAISE EXCEPTION 'Tipo de comissão inválido: %.', p_commission_kind;
  END IF;

  IF p_default_percentage IS NULL OR p_default_percentage <= 0 OR p_default_percentage > 100 THEN
    RAISE EXCEPTION 'Percentual da comissão deve ser maior que zero e menor ou igual a 100.';
  END IF;

  IF p_commission_date IS NULL OR p_issue_date IS NULL OR p_competence_date IS NULL OR p_first_due_date IS NULL THEN
    RAISE EXCEPTION 'Datas da comissão, emissão, competência e primeiro vencimento são obrigatórias.';
  END IF;

  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Selecione ao menos um item para a comissão.';
  END IF;

  SELECT p.role, p.store_id
    INTO v_user_role, v_user_store_id
  FROM public.profiles p
  WHERE p.id = v_user_id;

  SELECT l.store_id, l.name
    INTO v_store_id, v_auction_name
  FROM public.leiloes l
  WHERE l.id = p_auction_id;

  IF v_store_id IS NULL THEN
    RAISE EXCEPTION 'Leilão não encontrado.';
  END IF;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND NOT (
    v_store_id = v_user_store_id
    OR EXISTS (
      SELECT 1
      FROM public.user_stores us
      WHERE us.user_id = v_user_id
        AND us.store_id = v_store_id
    )
  ) THEN
    RAISE EXCEPTION 'Usuário sem acesso à fazenda do leilão informado.';
  END IF;

  IF p_document_type IS NOT NULL AND p_document_number IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.accounts_payable ap
      WHERE ap.supplier_id = p_supplier_id
        AND ap.document_type = p_document_type
        AND ap.document_number = p_document_number
    ) THEN
      RAISE EXCEPTION 'Já existe um título com o mesmo tipo e número de documento para este fornecedor.';
    END IF;
  END IF;

  FOR v_item IN
    SELECT value
    FROM jsonb_array_elements(p_items)
  LOOP
    v_item_type := v_item ->> 'item_type';
    v_item_id := (v_item ->> 'item_id')::UUID;
    v_purchase_amount := ROUND(COALESCE((v_item ->> 'purchase_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_item_percentage := ROUND(COALESCE((v_item ->> 'commission_percentage')::NUMERIC, p_default_percentage)::NUMERIC, 4);
    v_item_amount := ROUND(COALESCE((v_item ->> 'commission_amount')::NUMERIC, 0)::NUMERIC, 2);

    IF v_item_type NOT IN ('animal', 'pregnancy', 'aspiration') THEN
      RAISE EXCEPTION 'Tipo de item inválido na comissão: %.', v_item_type;
    END IF;

    IF v_item_id IS NULL THEN
      RAISE EXCEPTION 'Todos os itens da comissão precisam ter um cadastro válido.';
    END IF;

    IF v_item_amount <= 0 THEN
      RAISE EXCEPTION 'Todos os itens da comissão precisam ter valor maior que zero.';
    END IF;

    CASE v_item_type
      WHEN 'animal' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.animals a
        WHERE a.id = v_item_id;
      WHEN 'pregnancy' THEN
        SELECT p.store_id, p.name, p.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.pregnancy_management p
        WHERE p.id = v_item_id;
      WHEN 'aspiration' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.aspiration_management a
        WHERE a.id = v_item_id;
    END CASE;

    IF v_item_store_id IS NULL THEN
      RAISE EXCEPTION 'Cadastro relacionado não encontrado para o item informado.';
    END IF;

    IF v_item_store_id <> v_store_id THEN
      RAISE EXCEPTION 'Todos os itens da comissão devem pertencer à mesma fazenda do leilão selecionado.';
    END IF;

    v_total_amount := v_total_amount + v_item_amount;
  END LOOP;

  IF v_total_amount <= 0 THEN
    RAISE EXCEPTION 'O valor total da comissão deve ser maior que zero.';
  END IF;

  IF p_installments IS NULL OR jsonb_typeof(p_installments) <> 'array' OR jsonb_array_length(p_installments) = 0 THEN
    p_installments := jsonb_build_array(
      jsonb_build_object(
        'installment_number', 1,
        'due_date', p_first_due_date,
        'amount', ROUND(v_total_amount::NUMERIC, 2)
      )
    );
  END IF;

  v_description := COALESCE(
    NULLIF(BTRIM(p_description), ''),
    FORMAT(
      'Comissão de %s - %s',
      CASE WHEN p_commission_kind = 'purchase' THEN 'Compra' ELSE 'Venda' END,
      COALESCE(v_auction_name, 'Leilão')
    )
  );

  INSERT INTO public.commissions (
    auction_id,
    supplier_id,
    product_id,
    store_id,
    commission_kind,
    default_percentage,
    description,
    document_type,
    document_number,
    negotiation_method,
    commission_date,
    issue_date,
    first_due_date,
    competence_date,
    total_amount,
    installment_count,
    notes,
    created_by
  )
  VALUES (
    p_auction_id,
    p_supplier_id,
    p_product_id,
    v_store_id,
    p_commission_kind,
    ROUND(p_default_percentage::NUMERIC, 4),
    v_description,
    p_document_type,
    p_document_number,
    p_negotiation_method,
    p_commission_date,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(v_total_amount::NUMERIC, 2),
    GREATEST(jsonb_array_length(p_installments), 1),
    NULLIF(BTRIM(p_notes), ''),
    v_user_id
  )
  RETURNING id, code
    INTO v_commission_id, v_commission_code;

  v_payable_description := FORMAT('Comissão #%s - %s', v_commission_code, v_description);

  INSERT INTO public.accounts_payable (
    supplier_id,
    commission_id,
    description,
    document_type,
    document_number,
    issue_date,
    due_date,
    data_competencia,
    amount,
    total_amount,
    notes,
    status,
    store_id,
    account_id,
    created_by,
    updated_by
  )
  VALUES (
    p_supplier_id,
    v_commission_id,
    v_payable_description,
    p_document_type,
    p_document_number,
    p_issue_date,
    p_first_due_date,
    p_competence_date,
    ROUND(v_total_amount::NUMERIC, 2),
    ROUND(v_total_amount::NUMERIC, 2),
    NULLIF(BTRIM(p_notes), ''),
    'pending',
    v_store_id,
    NULL,
    v_user_id,
    v_user_id
  )
  RETURNING id
    INTO v_payable_id;

  FOR v_item IN
    SELECT value
    FROM jsonb_array_elements(p_items)
  LOOP
    v_display_order := v_display_order + 1;
    v_item_type := v_item ->> 'item_type';
    v_item_id := (v_item ->> 'item_id')::UUID;
    v_purchase_amount := ROUND(COALESCE((v_item ->> 'purchase_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_item_percentage := ROUND(COALESCE((v_item ->> 'commission_percentage')::NUMERIC, p_default_percentage)::NUMERIC, 4);
    v_item_amount := ROUND(COALESCE((v_item ->> 'commission_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_source_type := COALESCE(NULLIF(v_item ->> 'source_type', ''), 'manual');

    CASE v_item_type
      WHEN 'animal' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.animals a
        WHERE a.id = v_item_id;
      WHEN 'pregnancy' THEN
        SELECT p.store_id, p.name, p.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.pregnancy_management p
        WHERE p.id = v_item_id;
      WHEN 'aspiration' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.aspiration_management a
        WHERE a.id = v_item_id;
    END CASE;

    INSERT INTO public.commission_items (
      commission_id,
      source_type,
      item_type,
      animal_id,
      pregnancy_id,
      aspiration_id,
      item_name,
      item_code,
      purchase_amount,
      commission_percentage,
      commission_amount,
      display_order
    )
    VALUES (
      v_commission_id,
      v_source_type,
      v_item_type,
      CASE WHEN v_item_type = 'animal' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'pregnancy' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'aspiration' THEN v_item_id ELSE NULL END,
      v_item_name,
      v_item_code,
      v_purchase_amount,
      v_item_percentage,
      v_item_amount,
      v_display_order
    );

    INSERT INTO public.accounts_payable_items (
      account_payable_id,
      product_id,
      quantity,
      unit_price,
      total_price,
      store_id
    )
    VALUES (
      v_payable_id,
      p_product_id,
      1,
      v_item_amount,
      v_item_amount,
      v_store_id
    )
    RETURNING id
      INTO v_payable_item_id;

    INSERT INTO public.accounts_payable_item_allocations (
      account_payable_item_id,
      allocation_type,
      animal_id,
      aspiration_id,
      pregnancy_id
    )
    VALUES (
      v_payable_item_id,
      v_item_type,
      CASE WHEN v_item_type = 'animal' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'aspiration' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'pregnancy' THEN v_item_id ELSE NULL END
    );
  END LOOP;

  FOR v_installment IN
    SELECT value
    FROM jsonb_array_elements(p_installments)
  LOOP
    v_installment_count := v_installment_count + 1;
    v_installment_number := COALESCE((v_installment ->> 'installment_number')::INTEGER, v_installment_count);
    v_installment_due_date := (v_installment ->> 'due_date')::DATE;
    v_installment_amount := ROUND(COALESCE((v_installment ->> 'amount')::NUMERIC, 0)::NUMERIC, 2);

    IF v_installment_due_date IS NULL THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter data de vencimento.';
    END IF;

    IF v_installment_amount <= 0 THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter valor maior que zero.';
    END IF;

    v_installment_total := v_installment_total + v_installment_amount;

    INSERT INTO public.accounts_payable_installments (
      account_payable_id,
      installment_number,
      due_date,
      amount,
      status
    )
    VALUES (
      v_payable_id,
      v_installment_number,
      v_installment_due_date,
      v_installment_amount,
      'pending'
    );
  END LOOP;

  IF ABS(v_installment_total - ROUND(v_total_amount::NUMERIC, 2)) > 0.01 THEN
    RAISE EXCEPTION 'A soma das parcelas deve ser igual ao valor total da comissão.';
  END IF;

  UPDATE public.commissions
  SET installment_count = v_installment_count
  WHERE id = v_commission_id;

  RETURN QUERY
  SELECT v_commission_id, v_commission_code, v_payable_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_commission_with_payable(
  p_commission_id UUID,
  p_auction_id UUID,
  p_supplier_id UUID,
  p_commission_kind TEXT,
  p_default_percentage NUMERIC,
  p_product_id UUID,
  p_commission_date DATE,
  p_issue_date DATE,
  p_competence_date DATE,
  p_first_due_date DATE,
  p_document_type TEXT DEFAULT NULL,
  p_document_number TEXT DEFAULT NULL,
  p_description TEXT DEFAULT NULL,
  p_notes TEXT DEFAULT NULL,
  p_negotiation_method TEXT DEFAULT NULL,
  p_items JSONB DEFAULT '[]'::jsonb,
  p_installments JSONB DEFAULT '[]'::jsonb
)
RETURNS TABLE (
  commission_id UUID,
  commission_code BIGINT,
  account_payable_id UUID
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_user_role public.user_role;
  v_user_store_id UUID;
  v_existing_commission RECORD;
  v_payable_id UUID;
  v_store_id UUID;
  v_auction_name TEXT;
  v_description TEXT;
  v_payable_description TEXT;
  v_total_amount NUMERIC(12, 2) := 0;
  v_payable_item_id UUID;
  v_item JSONB;
  v_item_id UUID;
  v_item_type TEXT;
  v_item_store_id UUID;
  v_item_name TEXT;
  v_item_code TEXT;
  v_purchase_amount NUMERIC(12, 2);
  v_item_percentage NUMERIC(7, 4);
  v_item_amount NUMERIC(12, 2);
  v_source_type TEXT;
  v_display_order INTEGER := 0;
  v_installment JSONB;
  v_installment_count INTEGER := 0;
  v_installment_number INTEGER;
  v_installment_due_date DATE;
  v_installment_amount NUMERIC(12, 2);
  v_installment_total NUMERIC(12, 2) := 0;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF p_commission_id IS NULL THEN
    RAISE EXCEPTION 'Comissão inválida para atualização.';
  END IF;

  IF NOT public.user_has_permission('contas_pagar', 'write'::public.permission_type) THEN
    RAISE EXCEPTION 'Usuário sem permissão para editar comissões.';
  END IF;

  IF p_auction_id IS NULL OR p_supplier_id IS NULL OR p_product_id IS NULL THEN
    RAISE EXCEPTION 'Leilão, fornecedor e produto financeiro são obrigatórios.';
  END IF;

  IF p_commission_kind NOT IN ('purchase', 'sale') THEN
    RAISE EXCEPTION 'Tipo de comissão inválido: %.', p_commission_kind;
  END IF;

  IF p_default_percentage IS NULL OR p_default_percentage <= 0 OR p_default_percentage > 100 THEN
    RAISE EXCEPTION 'Percentual da comissão deve ser maior que zero e menor ou igual a 100.';
  END IF;

  IF p_commission_date IS NULL OR p_issue_date IS NULL OR p_competence_date IS NULL OR p_first_due_date IS NULL THEN
    RAISE EXCEPTION 'Datas da comissão, emissão, competência e primeiro vencimento são obrigatórias.';
  END IF;

  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Selecione ao menos um item para a comissão.';
  END IF;

  SELECT p.role, p.store_id
    INTO v_user_role, v_user_store_id
  FROM public.profiles p
  WHERE p.id = v_user_id;

  SELECT c.id, c.code, c.store_id
    INTO v_existing_commission
  FROM public.commissions c
  WHERE c.id = p_commission_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Comissão não encontrada.';
  END IF;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND NOT (
    v_existing_commission.store_id = v_user_store_id
    OR EXISTS (
      SELECT 1
      FROM public.user_stores us
      WHERE us.user_id = v_user_id
        AND us.store_id = v_existing_commission.store_id
    )
  ) THEN
    RAISE EXCEPTION 'Usuário sem acesso à fazenda desta comissão.';
  END IF;

  SELECT ap.id
    INTO v_payable_id
  FROM public.accounts_payable ap
  WHERE ap.commission_id = p_commission_id
  FOR UPDATE;

  IF v_payable_id IS NULL THEN
    RAISE EXCEPTION 'Título financeiro vinculado à comissão não encontrado.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable ap
    WHERE ap.id = v_payable_id
      AND (
        ap.payment_date IS NOT NULL
        OR COALESCE(ap.status, 'pending') = 'pagamento_suspenso'
      )
  ) THEN
    RAISE EXCEPTION 'Comissões com pagamento realizado ou suspenso não podem ser editadas.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_installments api
    WHERE api.account_payable_id = v_payable_id
      AND (
        api.payment_date IS NOT NULL
        OR COALESCE(api.status, 'pending') = 'pagamento_suspenso'
      )
  ) THEN
    RAISE EXCEPTION 'Comissões com parcelas pagas ou suspensas não podem ser editadas.';
  END IF;

  SELECT l.store_id, l.name
    INTO v_store_id, v_auction_name
  FROM public.leiloes l
  WHERE l.id = p_auction_id;

  IF v_store_id IS NULL THEN
    RAISE EXCEPTION 'Leilão não encontrado.';
  END IF;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND NOT (
    v_store_id = v_user_store_id
    OR EXISTS (
      SELECT 1
      FROM public.user_stores us
      WHERE us.user_id = v_user_id
        AND us.store_id = v_store_id
    )
  ) THEN
    RAISE EXCEPTION 'Usuário sem acesso à fazenda do leilão informado.';
  END IF;

  IF p_document_type IS NOT NULL AND p_document_number IS NOT NULL THEN
    IF EXISTS (
      SELECT 1
      FROM public.accounts_payable ap
      WHERE ap.supplier_id = p_supplier_id
        AND ap.document_type = p_document_type
        AND ap.document_number = p_document_number
        AND ap.id <> v_payable_id
    ) THEN
      RAISE EXCEPTION 'Já existe um título com o mesmo tipo e número de documento para este fornecedor.';
    END IF;
  END IF;

  FOR v_item IN
    SELECT value
    FROM jsonb_array_elements(p_items)
  LOOP
    v_item_type := v_item ->> 'item_type';
    v_item_id := (v_item ->> 'item_id')::UUID;
    v_purchase_amount := ROUND(COALESCE((v_item ->> 'purchase_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_item_percentage := ROUND(COALESCE((v_item ->> 'commission_percentage')::NUMERIC, p_default_percentage)::NUMERIC, 4);
    v_item_amount := ROUND(COALESCE((v_item ->> 'commission_amount')::NUMERIC, 0)::NUMERIC, 2);

    IF v_item_type NOT IN ('animal', 'pregnancy', 'aspiration') THEN
      RAISE EXCEPTION 'Tipo de item inválido na comissão: %.', v_item_type;
    END IF;

    IF v_item_id IS NULL THEN
      RAISE EXCEPTION 'Todos os itens da comissão precisam ter um cadastro válido.';
    END IF;

    IF v_item_amount <= 0 THEN
      RAISE EXCEPTION 'Todos os itens da comissão precisam ter valor maior que zero.';
    END IF;

    CASE v_item_type
      WHEN 'animal' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.animals a
        WHERE a.id = v_item_id;
      WHEN 'pregnancy' THEN
        SELECT p.store_id, p.name, p.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.pregnancy_management p
        WHERE p.id = v_item_id;
      WHEN 'aspiration' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.aspiration_management a
        WHERE a.id = v_item_id;
    END CASE;

    IF v_item_store_id IS NULL THEN
      RAISE EXCEPTION 'Cadastro relacionado não encontrado para o item informado.';
    END IF;

    IF v_item_store_id <> v_store_id THEN
      RAISE EXCEPTION 'Todos os itens da comissão devem pertencer à mesma fazenda do leilão selecionado.';
    END IF;

    v_total_amount := v_total_amount + v_item_amount;
  END LOOP;

  IF v_total_amount <= 0 THEN
    RAISE EXCEPTION 'O valor total da comissão deve ser maior que zero.';
  END IF;

  IF p_installments IS NULL OR jsonb_typeof(p_installments) <> 'array' OR jsonb_array_length(p_installments) = 0 THEN
    p_installments := jsonb_build_array(
      jsonb_build_object(
        'installment_number', 1,
        'due_date', p_first_due_date,
        'amount', ROUND(v_total_amount::NUMERIC, 2)
      )
    );
  END IF;

  DELETE FROM public.accounts_payable_item_allocations
  WHERE account_payable_item_id IN (
    SELECT api.id
    FROM public.accounts_payable_items api
    WHERE api.account_payable_id = v_payable_id
  );

  DELETE FROM public.accounts_payable_items
  WHERE account_payable_id = v_payable_id;

  DELETE FROM public.accounts_payable_installments
  WHERE account_payable_id = v_payable_id;

  DELETE FROM public.commission_items
  WHERE commission_id = p_commission_id;

  v_description := COALESCE(
    NULLIF(BTRIM(p_description), ''),
    FORMAT(
      'Comissão de %s - %s',
      CASE WHEN p_commission_kind = 'purchase' THEN 'Compra' ELSE 'Venda' END,
      COALESCE(v_auction_name, 'Leilão')
    )
  );

  UPDATE public.commissions
  SET auction_id = p_auction_id,
      supplier_id = p_supplier_id,
      product_id = p_product_id,
      store_id = v_store_id,
      commission_kind = p_commission_kind,
      default_percentage = ROUND(p_default_percentage::NUMERIC, 4),
      description = v_description,
      document_type = p_document_type,
      document_number = p_document_number,
      negotiation_method = p_negotiation_method,
      commission_date = p_commission_date,
      issue_date = p_issue_date,
      first_due_date = p_first_due_date,
      competence_date = p_competence_date,
      total_amount = ROUND(v_total_amount::NUMERIC, 2),
      installment_count = GREATEST(jsonb_array_length(p_installments), 1),
      notes = NULLIF(BTRIM(p_notes), '')
  WHERE id = p_commission_id;

  v_payable_description := FORMAT('Comissão #%s - %s', v_existing_commission.code, v_description);

  UPDATE public.accounts_payable
  SET supplier_id = p_supplier_id,
      description = v_payable_description,
      document_type = p_document_type,
      document_number = p_document_number,
      issue_date = p_issue_date,
      due_date = p_first_due_date,
      data_competencia = p_competence_date,
      amount = ROUND(v_total_amount::NUMERIC, 2),
      total_amount = ROUND(v_total_amount::NUMERIC, 2),
      notes = NULLIF(BTRIM(p_notes), ''),
      status = 'pending',
      store_id = v_store_id,
      updated_by = v_user_id,
      payment_date = NULL
  WHERE id = v_payable_id;

  FOR v_item IN
    SELECT value
    FROM jsonb_array_elements(p_items)
  LOOP
    v_display_order := v_display_order + 1;
    v_item_type := v_item ->> 'item_type';
    v_item_id := (v_item ->> 'item_id')::UUID;
    v_purchase_amount := ROUND(COALESCE((v_item ->> 'purchase_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_item_percentage := ROUND(COALESCE((v_item ->> 'commission_percentage')::NUMERIC, p_default_percentage)::NUMERIC, 4);
    v_item_amount := ROUND(COALESCE((v_item ->> 'commission_amount')::NUMERIC, 0)::NUMERIC, 2);
    v_source_type := COALESCE(NULLIF(v_item ->> 'source_type', ''), 'manual');

    CASE v_item_type
      WHEN 'animal' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.animals a
        WHERE a.id = v_item_id;
      WHEN 'pregnancy' THEN
        SELECT p.store_id, p.name, p.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.pregnancy_management p
        WHERE p.id = v_item_id;
      WHEN 'aspiration' THEN
        SELECT a.store_id, a.name, a.code::TEXT
          INTO v_item_store_id, v_item_name, v_item_code
        FROM public.aspiration_management a
        WHERE a.id = v_item_id;
    END CASE;

    INSERT INTO public.commission_items (
      commission_id,
      source_type,
      item_type,
      animal_id,
      pregnancy_id,
      aspiration_id,
      item_name,
      item_code,
      purchase_amount,
      commission_percentage,
      commission_amount,
      display_order
    )
    VALUES (
      p_commission_id,
      v_source_type,
      v_item_type,
      CASE WHEN v_item_type = 'animal' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'pregnancy' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'aspiration' THEN v_item_id ELSE NULL END,
      v_item_name,
      v_item_code,
      v_purchase_amount,
      v_item_percentage,
      v_item_amount,
      v_display_order
    );

    INSERT INTO public.accounts_payable_items (
      account_payable_id,
      product_id,
      quantity,
      unit_price,
      total_price,
      store_id
    )
    VALUES (
      v_payable_id,
      p_product_id,
      1,
      v_item_amount,
      v_item_amount,
      v_store_id
    )
    RETURNING id
      INTO v_payable_item_id;

    INSERT INTO public.accounts_payable_item_allocations (
      account_payable_item_id,
      allocation_type,
      animal_id,
      aspiration_id,
      pregnancy_id
    )
    VALUES (
      v_payable_item_id,
      v_item_type,
      CASE WHEN v_item_type = 'animal' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'aspiration' THEN v_item_id ELSE NULL END,
      CASE WHEN v_item_type = 'pregnancy' THEN v_item_id ELSE NULL END
    );
  END LOOP;

  FOR v_installment IN
    SELECT value
    FROM jsonb_array_elements(p_installments)
  LOOP
    v_installment_count := v_installment_count + 1;
    v_installment_number := COALESCE((v_installment ->> 'installment_number')::INTEGER, v_installment_count);
    v_installment_due_date := (v_installment ->> 'due_date')::DATE;
    v_installment_amount := ROUND(COALESCE((v_installment ->> 'amount')::NUMERIC, 0)::NUMERIC, 2);

    IF v_installment_due_date IS NULL THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter data de vencimento.';
    END IF;

    IF v_installment_amount <= 0 THEN
      RAISE EXCEPTION 'Todas as parcelas precisam ter valor maior que zero.';
    END IF;

    v_installment_total := v_installment_total + v_installment_amount;

    INSERT INTO public.accounts_payable_installments (
      account_payable_id,
      installment_number,
      due_date,
      amount,
      status
    )
    VALUES (
      v_payable_id,
      v_installment_number,
      v_installment_due_date,
      v_installment_amount,
      'pending'
    );
  END LOOP;

  IF ABS(v_installment_total - ROUND(v_total_amount::NUMERIC, 2)) > 0.01 THEN
    RAISE EXCEPTION 'A soma das parcelas deve ser igual ao valor total da comissão.';
  END IF;

  UPDATE public.commissions
  SET installment_count = v_installment_count
  WHERE id = p_commission_id;

  RETURN QUERY
  SELECT p_commission_id, v_existing_commission.code, v_payable_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.delete_commission_with_payable(
  p_commission_id UUID
)
RETURNS TABLE (
  commission_id UUID,
  commission_code BIGINT,
  deleted_payables INTEGER
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID := auth.uid();
  v_user_role public.user_role;
  v_user_store_id UUID;
  v_commission RECORD;
  v_deleted_payables INTEGER := 0;
  v_payable_ids UUID[];
  v_installment_ids UUID[];
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuário não autenticado.';
  END IF;

  IF p_commission_id IS NULL THEN
    RAISE EXCEPTION 'Informe a comissão que será excluída.';
  END IF;

  IF NOT public.user_has_permission('contas_pagar', 'write'::public.permission_type) THEN
    RAISE EXCEPTION 'Usuário sem permissão para excluir comissões.';
  END IF;

  SELECT p.role, p.store_id
    INTO v_user_role, v_user_store_id
  FROM public.profiles p
  WHERE p.id = v_user_id;

  SELECT c.id, c.code, c.store_id
    INTO v_commission
  FROM public.commissions c
  WHERE c.id = p_commission_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Comissão não encontrada.';
  END IF;

  IF v_user_role IS DISTINCT FROM 'admin'::public.user_role AND NOT (
    v_commission.store_id = v_user_store_id
    OR EXISTS (
      SELECT 1
      FROM public.user_stores us
      WHERE us.user_id = v_user_id
        AND us.store_id = v_commission.store_id
    )
  ) THEN
    RAISE EXCEPTION 'Usuário sem acesso à fazenda desta comissão.';
  END IF;

  SELECT ARRAY_AGG(ap.id ORDER BY ap.id)
    INTO v_payable_ids
  FROM public.accounts_payable ap
  WHERE ap.commission_id = p_commission_id;

  SELECT ARRAY_AGG(api.id ORDER BY api.id)
    INTO v_installment_ids
  FROM public.accounts_payable_installments api
  JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
  WHERE ap.commission_id = p_commission_id;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable ap
    WHERE ap.commission_id = p_commission_id
      AND (
        ap.payment_date IS NOT NULL
        OR COALESCE(ap.status, 'pending') = 'pagamento_suspenso'
      )
  ) THEN
    RAISE EXCEPTION 'Somente comissões com contas a pagar pendentes e sem pagamentos podem ser excluídas.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.accounts_payable_installments api
    JOIN public.accounts_payable ap ON ap.id = api.account_payable_id
    WHERE ap.commission_id = p_commission_id
      AND (
        api.payment_date IS NOT NULL
        OR COALESCE(api.status, 'pending') = 'pagamento_suspenso'
      )
  ) THEN
    RAISE EXCEPTION 'Somente comissões com parcelas pendentes e sem pagamentos podem ser excluídas.';
  END IF;

  SELECT COUNT(*)
    INTO v_deleted_payables
  FROM public.accounts_payable ap
  WHERE ap.commission_id = p_commission_id;

  IF COALESCE(array_length(v_payable_ids, 1), 0) > 0 THEN
    DELETE FROM public.accounts_payable_payments
    WHERE account_payable_id = ANY(v_payable_ids);

    DELETE FROM public.financial_transactions
    WHERE (
      reference_type = 'accounts_payable'
      AND reference_id = ANY(v_payable_ids)
    )
    OR (
      reference_type = 'accounts_payable_installments'
      AND COALESCE(array_length(v_installment_ids, 1), 0) > 0
      AND reference_id = ANY(v_installment_ids)
    );

    DELETE FROM public.accounts_payable
    WHERE id = ANY(v_payable_ids);
  END IF;

  DELETE FROM public.commissions
  WHERE id = p_commission_id;

  RETURN QUERY
  SELECT v_commission.id, v_commission.code, v_deleted_payables;
END;
$$;

GRANT EXECUTE ON FUNCTION public.create_commission_with_payable(UUID, UUID, TEXT, NUMERIC, UUID, DATE, DATE, DATE, DATE, TEXT, TEXT, TEXT, TEXT, TEXT, JSONB, JSONB) TO authenticated;
GRANT EXECUTE ON FUNCTION public.update_commission_with_payable(UUID, UUID, UUID, TEXT, NUMERIC, UUID, DATE, DATE, DATE, DATE, TEXT, TEXT, TEXT, TEXT, TEXT, JSONB, JSONB) TO authenticated;
GRANT EXECUTE ON FUNCTION public.delete_commission_with_payable(UUID) TO authenticated;
