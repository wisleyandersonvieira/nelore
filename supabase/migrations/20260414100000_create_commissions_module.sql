CREATE TABLE public.commissions (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  code BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  auction_id UUID NOT NULL REFERENCES public.leiloes(id),
  supplier_id UUID NOT NULL REFERENCES public.suppliers(id),
  product_id UUID NOT NULL REFERENCES public.products(id),
  store_id UUID NOT NULL REFERENCES public.stores(id),
  commission_kind TEXT NOT NULL CHECK (commission_kind IN ('purchase', 'sale')),
  default_percentage NUMERIC(7, 4) NOT NULL CHECK (default_percentage > 0 AND default_percentage <= 100),
  description TEXT NOT NULL,
  document_type TEXT,
  document_number TEXT,
  negotiation_method TEXT,
  commission_date DATE NOT NULL,
  issue_date DATE NOT NULL,
  first_due_date DATE NOT NULL,
  competence_date DATE NOT NULL,
  total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount > 0),
  installment_count INTEGER NOT NULL DEFAULT 1 CHECK (installment_count > 0),
  notes TEXT,
  created_by UUID NOT NULL REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT commissions_code_key UNIQUE (code)
);

CREATE TABLE public.commission_items (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  commission_id UUID NOT NULL REFERENCES public.commissions(id) ON DELETE CASCADE,
  source_type TEXT NOT NULL CHECK (source_type IN ('auction', 'manual')),
  item_type TEXT NOT NULL CHECK (item_type IN ('animal', 'pregnancy', 'aspiration')),
  animal_id UUID REFERENCES public.animals(id),
  pregnancy_id UUID REFERENCES public.pregnancy_management(id),
  aspiration_id UUID REFERENCES public.aspiration_management(id),
  item_name TEXT NOT NULL,
  item_code TEXT,
  purchase_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (purchase_amount >= 0),
  commission_percentage NUMERIC(7, 4) NOT NULL DEFAULT 0 CHECK (commission_percentage >= 0 AND commission_percentage <= 100),
  commission_amount NUMERIC(12, 2) NOT NULL CHECK (commission_amount > 0),
  display_order INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT commission_items_item_scope_check CHECK (
    (item_type = 'animal' AND animal_id IS NOT NULL AND pregnancy_id IS NULL AND aspiration_id IS NULL) OR
    (item_type = 'pregnancy' AND animal_id IS NULL AND pregnancy_id IS NOT NULL AND aspiration_id IS NULL) OR
    (item_type = 'aspiration' AND animal_id IS NULL AND pregnancy_id IS NULL AND aspiration_id IS NOT NULL)
  )
);

